# Runs before each build:
#  1. web/build.py gzips web/index.html into src/web_page.h (fails the build if it fails or
#     the page is over its 20 KB budget).
#  2. Writes src/version.h with the firmware version (git describe, else the build date).
# Both files are generated and git-ignored; each is only rewritten when it changes, so an
# unchanged page or version does not force a rebuild.
import datetime
import os
import subprocess
import sys

Import("env")  # noqa: F821  (provided by PlatformIO)

src = env.subst("$PROJECT_SRC_DIR")  # noqa: F821  (firmware/src)
root = os.path.dirname(src)
build = os.path.join(root, "..", "web", "build.py")

if subprocess.call([sys.executable, build]) != 0:
    print("web/build.py failed: the web page could not be built into src/web_page.h")
    env.Exit(1)  # noqa: F821

try:
    version = subprocess.check_output(["git", "describe", "--always", "--dirty", "--tags"], cwd=root,
                                      stderr=subprocess.DEVNULL, text=True).strip()
except Exception:
    version = ""
if not version:
    version = "build " + datetime.date.today().isoformat()
version = version.replace("\\", "").replace('"', "")

header = ("// Generated by scripts/prebuild.py. Do not edit.\n#pragma once\n"
          f'#define FW_VERSION "{version}"\n')
dst = os.path.join(src, "version.h")
if not os.path.exists(dst) or open(dst).read() != header:
    with open(dst, "w") as f:
        f.write(header)
print(f"Firmware version: {version}")
