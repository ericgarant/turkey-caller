#!/usr/bin/env python3
"""Gzip the web page into the firmware: web/index.html -> firmware/src/web_page.h.

The page is compiled into the app binary, not stored in LittleFS, so updating it
never wipes sounds uploaded from the phone (uploadfs rewrites the whole LittleFS).
The firmware serves kWebPageGz at "/" with Content-Encoding: gzip. Plain Python 3,
no packages, so a PlatformIO pre-build extra_script can run it.
"""
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "index.html"
OUT = ROOT.parent / "firmware" / "src" / "web_page.h"
BUDGET = 20 * 1024  # keep the page small: it shares the radio with Bluetooth audio


def squeeze(html: str) -> str:
    # Drop leading indentation and blank lines. Safe for this page: no <pre> blocks
    # and no multi-line string literals in the script.
    return "\n".join(line.strip() for line in html.splitlines() if line.strip())


def main() -> int:
    html = squeeze(SRC.read_text(encoding="utf-8"))
    data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
    rows = ",\n".join(",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
    header = (
        "// Generated by web/build.py from web/index.html. Do not edit.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
        f"static const uint8_t kWebPageGz[] = {{\n{rows}\n}};\n"
        "static const size_t kWebPageGzLen = sizeof(kWebPageGz);\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not OUT.exists() or OUT.read_text() != header:  # unchanged file keeps the build cache valid
        OUT.write_text(header)
    print(f"Web page: {len(data)} bytes gzipped ({len(data) * 100 // BUDGET}% of the {BUDGET // 1024} KB budget) -> {OUT.relative_to(ROOT.parent)}")
    if len(data) > BUDGET:
        print("Web page is over budget", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
